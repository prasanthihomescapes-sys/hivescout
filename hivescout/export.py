"""Turn web-probe findings into a Playwright regression spec for the target repo.

The spec encodes the *expected* behaviour (tell the user, offer a way out), so it fails until the gap is fixed
and then guards against regressions. One test per (route, fault) pair.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from .findings import Finding
from .probe.faults import FAULTS

ERROR_RX = r"/went wrong|error|failed|couldn.?t|could not|unable|try again|offline|no (internet|connection)|timed out|taking longer|expired|sign in/i"
STACK_RX = r"/Traceback|TypeError|ReferenceError|Cannot read propert|Unexpected token|Unhandled Runtime Error|\[object Object\]/"
RECOVERY_RX = r"/retry|try again|reload|refresh|back|home|contact|sign in|log in/i"
EMPTY_RX = r"/no \w+ (yet|found)|nothing (here|yet)|get started|create your first|add your first|no results|no data/i"


def _route_code(fault_name: str, api_pattern: str) -> tuple[str, str, int]:
    """(setup before goto, action after goto, wait ms)."""
    f = FAULTS[fault_name]
    pat = json.dumps(api_pattern)
    skip_doc = "if (route.request().resourceType() === \"document\") return route.continue();"
    if f.kind in ("status", "body"):
        body = json.dumps(f.body)
        return (f"await context.route({pat}, (route) => {{ {skip_doc} return route.fulfill({{ status: {f.status}, "
                f"contentType: {json.dumps(f.content_type)}, body: {body} }}); }});", "", 2500)
    if f.kind == "abort":
        return (f"await context.route({pat}, (route) => {{ {skip_doc} return route.abort(\"internetdisconnected\"); }});",
                "await context.setOffline(true);", 2500)
    if f.kind == "hang":
        return (f"await context.route({pat}, (route) => {{ {skip_doc} return new Promise(() => {{}}); }});", "", 9000)
    if f.kind == "delay":
        return (f"await context.route({pat}, async (route) => {{ {skip_doc} await new Promise((r) => setTimeout(r, "
                f"{f.delay_ms})); return route.continue(); }});", "", 9000)
    return ("", "", 2500)


def spec(findings: list[Finding], api_pattern: str = "**/api/**") -> str:
    pairs: dict[tuple[str, str], list[Finding]] = {}
    for f in findings:
        if f.channel == "web" and f.route and f.fault and f.fault in FAULTS and f.fault != "baseline":
            pairs.setdefault((f.route, f.fault), []).append(f)
    out = [
        "// Generated by hivescout on " + date.today().isoformat() + ". Each test encodes what the user should see",
        "// when the backend misbehaves. It fails until the finding is fixed; keep it as a regression guard.",
        'import { test, expect } from "@playwright/test";',
        "",
        'test.describe("hivescout: non-happy states", () => {',
    ]
    for (route, fault), fs in sorted(pairs.items()):
        setup, after, wait = _route_code(fault, api_pattern)
        rules = ", ".join(sorted({f.rule for f in fs}))
        name = f"{route} under {fault}: user is told and can recover ({rules})"
        out.append(f"  test({json.dumps(name)}, async ({{ page, context }}) => {{")
        for f in fs:
            out.append(f"    // {f.rule}: {f.title}")
        if setup:
            out.append(f"    {setup}")
        out.append(f"    await page.goto({json.dumps(route)});")
        if after:
            out.append(f"    {after}")
        out.append(f"    await page.waitForTimeout({wait});")
        out.append('    const body = page.locator("body");')
        out.append(f"    await expect(body).not.toHaveText({STACK_RX});")
        if fault == "empty":
            out.append(f"    await expect(body).toHaveText({EMPTY_RX});")
        else:
            out.append(f"    await expect(body).toHaveText({ERROR_RX});")
            out.append("    await expect(page.getByRole(\"button\", { name: " + RECOVERY_RX + " })"
                       ".or(page.getByRole(\"link\", { name: " + RECOVERY_RX + " })).first()).toBeVisible();")
        out.append("  });")
        out.append("")
    out.append("});")
    return "\n".join(out) + "\n"


def write(findings: list[Finding], out: Path, api_pattern: str = "**/api/**") -> int:
    text = spec(findings, api_pattern)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return text.count("  test(")
